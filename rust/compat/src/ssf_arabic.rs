pub fn is_arabic(c: u16) -> bool {
    (0x600..=0x6ff).contains(&c)
}
/// Low 16 bits contain the resulting code unit; bit 16 is the native bool.
pub fn replace(c: u16, form: u32) -> u32 {
    if !is_arabic(c) {
        return u32::from(c);
    }
    let value = FORMS[usize::from(c - 0x600)]
        .get(form as usize)
        .copied()
        .unwrap_or(c);
    (1 << 16) | u32::from(value)
}
pub fn neighbors(c: u16, previous: u16, next: u16) -> u32 {
    let form = match (is_arabic(previous), is_arabic(next)) {
        (false, false) => 0,
        (false, true) => 1,
        (true, true) => 2,
        (true, false) => 3,
    };
    replace(c, form)
}
